#!/usr/bin/env python3
"""collect.py [INCOMING] -- fold new per-build results into layouts/ and
regenerate generated/.

INCOMING holds <build>/{layout.txt,version.txt,meta.json} directories, as the
extract jobs upload them.  Builds are grouped by their ARM_HV_STATE_VER: Apple
bumps it whenever the context layout changes, so every build of one version
should dump the same layout -- a version whose builds disagree is reported in
generated/CONFLICTS.md rather than averaged over.
"""
import json, os, shutil, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fields import BLOCKS, FIELDS, RO, RW, fields, load, members

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LAYOUTS, GEN = os.path.join(ROOT, "layouts"), os.path.join(ROOT, "generated")


def vkey(v):
    return tuple(int(x) for x in v.split("."))


def main():
    if len(sys.argv) > 1:
        for b in sorted(os.listdir(sys.argv[1])):
            src = os.path.join(sys.argv[1], b)
            if os.path.isfile(os.path.join(src, "layout.txt")):
                dst = os.path.join(LAYOUTS, b)
                shutil.rmtree(dst, ignore_errors=True)
                shutil.copytree(src, dst, ignore=shutil.ignore_patterns("lldb.log"))
    builds = {}
    for b in sorted(os.listdir(LAYOUTS)):
        d = os.path.join(LAYOUTS, b)
        if not os.path.isfile(os.path.join(d, "layout.txt")):
            continue
        word, ver = open(os.path.join(d, "version.txt")).read().split()[:2]
        meta = json.load(open(os.path.join(d, "meta.json"))) if os.path.exists(
            os.path.join(d, "meta.json")) else {}
        types = load(os.path.join(d, "layout.txt"))
        builds[b] = {"version": ver, "word": word, "meta": meta, "types": types,
                     "fields": fields(types)}

    versions, conflicts = {}, []
    for b, info in sorted(builds.items()):
        versions.setdefault(info["version"], []).append(b)
    out = {"versions": {}, "builds": {}}
    for ver in sorted(versions, key=vkey):
        bs = versions[ver]
        ref = builds[bs[0]]
        for other in bs[1:]:
            diff = [t for t in [RW, RO] + BLOCKS if builds[other]["types"].get(t) != ref["types"].get(t)]
            if diff:
                conflicts.append("%s: %s and %s differ in %s" % (ver, bs[0], other, ", ".join(diff)))
        out["versions"][ver] = {
            "word": ref["word"], "builds": bs,
            "fields": {k: list(v) if v else None for k, v in ref["fields"].items()},
            # [name, offset in the block, size], in offset order
            "blocks": {blk: [[m, v[0], v[1]] for m, v in sorted(members(ref["types"], blk).items(),
                                                                  key=lambda kv: kv[1][0])]
                       for blk in BLOCKS},
        }
    for b, info in sorted(builds.items()):
        out["builds"][b] = dict(info["meta"], version=info["version"])

    os.makedirs(GEN, exist_ok=True)
    with open(os.path.join(GEN, "layouts.json"), "w") as fh:
        json.dump(out, fh, indent=1, sort_keys=True)
        fh.write("\n")
    write_header(out)
    write_summary(out)
    with open(os.path.join(GEN, "CONFLICTS.md"), "w") as fh:
        fh.write("# Versions whose builds disagree\n\n")
        fh.write("".join("* %s\n" % c for c in conflicts) or "None.\n")
    print("%d builds, %d versions, %d conflicts" % (len(builds), len(versions), len(conflicts)))


def write_header(out):
    names = [f[0] for f in FIELDS]
    lines = [
        "/* Generated by tools/collect.py from Kernel Debug Kit DWARF -- do not edit. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "/* Offsets into the two-page hv guest context (RO page at +0x4000), and",
        " * sizes, of the fields a VMM touches.  0 size: not in this version. */",
        "typedef struct { uint16_t off; uint8_t size; } ohv_hv_field_t;",
        "",
        "typedef struct {",
        "    uint64_t ver;              /* ARM_HV_STATE_VER */",
        "    const char *builds;",
    ] + ["    ohv_hv_field_t %s;" % n for n in names] + [
        "} ohv_hv_layout_t;",
        "",
        "static const ohv_hv_layout_t ohv_hv_layouts[] = {",
    ]
    for ver, v in out["versions"].items():
        lines.append("    { /* %s */" % ver)
        lines.append("        .ver = %s," % v["word"])
        lines.append('        .builds = "%s",' % " ".join(v["builds"]))
        for n in names:
            f = v["fields"][n]
            lines.append("        .%s = { 0x%x, %d }," % (n, f[0], f[1]) if f else
                         "        .%s = { 0, 0 }," % n)
        lines.append("    },")
    lines += ["};", ""]
    open(os.path.join(GEN, "ohv_hv_layouts.h"), "w").write("\n".join(lines))


def write_summary(out):
    cols = ["rw_dbgregs", "rw_vgic_sysregs", "rw_controls", "rw_state_dirty", "rw_extregs",
            "ro_exit_esr", "ro_state_valid", "ro_ich_vtr", "ro_svcr", "ro_sme_ptr"]
    lines = ["# hv guest-context layouts", "",
             "From each Kernel Debug Kit's DWARF (`kernel.release.t8132`); offsets/sizes in bytes,",
             "RO page at +0x4000.", "",
             "| version | " + " | ".join(cols) + " | builds |",
             "|---" * (len(cols) + 2) + "|"]
    for ver, v in out["versions"].items():
        cells = []
        for c in cols:
            f = v["fields"][c]
            cells.append("0x%x/%d" % tuple(f) if f else "-")
        lines.append("| %s | %s | %s |" % (ver, " | ".join(cells), " ".join(v["builds"])))
    lines += ["", "| build | macOS | version | kernel | mirror's title |", "|---|---|---|---|---|"]
    for b, m in out["builds"].items():
        lines.append("| %s | %s | %s | %s | %s |" % (b, m.get("macos", ""), m["version"],
                                                    m.get("kernel", ""), m.get("release", "")))
    open(os.path.join(GEN, "SUMMARY.md"), "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
